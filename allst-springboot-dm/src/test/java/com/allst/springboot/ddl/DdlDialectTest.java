package com.allst.springboot.ddl;

import com.allst.springboot.common.BizException;
import com.allst.springboot.ddl.dialect.ClickHouseDialect;
import com.allst.springboot.ddl.dialect.DialectRouter;
import com.allst.springboot.ddl.dialect.DorisDialect;
import com.allst.springboot.ddl.dialect.GenericDialect;
import com.allst.springboot.ddl.dialect.HiveDialect;
import com.allst.springboot.ddl.dialect.ImpalaDialect;
import com.allst.springboot.ddl.dialect.MySqlDialect;
import com.allst.springboot.ddl.dialect.OracleDialect;
import com.allst.springboot.ddl.dialect.PostgreSqlDialect;
import com.allst.springboot.ddl.dialect.SqlServerDialect;
import com.allst.springboot.ddl.dialect.SqliteDialect;
import com.allst.springboot.ddl.meta.ColumnMeta;
import com.allst.springboot.ddl.meta.TableMeta;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.Arrays;

import static com.allst.springboot.ddl.meta.LogicalTypes.*;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * 各方言的 golden 断言：差异必须体现在能力钩子上，而不是靠 if-else 猜。
 */
class DdlDialectTest {

    private TableMeta table(String dialect) {
        return TableMeta.builder()
                .schemaName("demo").tableName("sample").dialect(dialect)
                .comment("示例表").tableOptions("ENGINE=InnoDB")
                .column(ColumnMeta.builder().columnName("id").logicalType(BIGINT)
                        .primaryKey(true).autoIncrement(true).comment("主键").ordinal(0).build())
                .column(ColumnMeta.builder().columnName("name").logicalType(STRING).length(64)
                        .nullable(false).comment("名称").ordinal(1).build())
                .column(ColumnMeta.builder().columnName("amount").logicalType(DECIMAL)
                        .precision(12).scale(2).ordinal(2).build())
                .column(ColumnMeta.builder().columnName("dt").logicalType(STRING)
                        .partition(true).ordinal(3).build())
                .build();
    }

    @Test
    @DisplayName("MySQL：反引号 + AUTO_INCREMENT + 内联注释 + 表选项 + 哈希分区")
    void mySql() {
        String sql = new MySqlDialect().generate(table("MYSQL")).getSql();
        assertThat(sql).contains("CREATE TABLE IF NOT EXISTS `demo`.`sample`");
        assertThat(sql).contains("`id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键'");
        assertThat(sql).contains("`name` varchar(64) NOT NULL COMMENT '名称'");
        assertThat(sql).contains("`amount` decimal(12,2)");
        assertThat(sql).contains("PRIMARY KEY (`id`)");
        assertThat(sql).contains("COMMENT='示例表'");
        assertThat(sql).contains("ENGINE=InnoDB");
        assertThat(sql).contains("PARTITION BY HASH (`dt`) PARTITIONS 4");
    }

    @Test
    @DisplayName("PostgreSQL：BIGSERIAL + 独立 COMMENT ON，无内联注释")
    void postgreSql() {
        com.allst.springboot.ddl.dialect.DdlOutput out = new PostgreSqlDialect().generate(table("POSTGRESQL"));
        String sql = out.getSql();
        assertThat(sql).contains("CREATE TABLE IF NOT EXISTS \"demo\".\"sample\"");
        assertThat(sql).contains("\"id\" bigserial NOT NULL");
        assertThat(sql).contains("\"amount\" numeric(12,2)");
        assertThat(sql).doesNotContain("COMMENT '主键'");
        assertThat(sql).contains("COMMENT ON TABLE \"demo\".\"sample\" IS '示例表'");
        assertThat(sql).contains("COMMENT ON COLUMN \"demo\".\"sample\".\"id\" IS '主键'");
        assertThat(out.getWarnings()).anyMatch(w -> w.contains("不支持分区"));
    }

    @Test
    @DisplayName("Oracle：大写双引号 + IDENTITY + COMMENT ON + 无 IF NOT EXISTS")
    void oracle() {
        String sql = new OracleDialect().generate(table("ORACLE")).getSql();
        assertThat(sql).contains("CREATE TABLE \"demo\".\"sample\"");
        assertThat(sql).doesNotContain("IF NOT EXISTS");
        assertThat(sql).contains("\"id\" number(19) NOT NULL GENERATED BY DEFAULT AS IDENTITY");
        assertThat(sql).contains("COMMENT ON TABLE \"demo\".\"sample\" IS '示例表'");
        assertThat(sql).contains("ENGINE=InnoDB");
    }

    @Test
    @DisplayName("SQL Server：方括号 + IDENTITY(1,1) + 扩展属性注释")
    void sqlServer() {
        String sql = new SqlServerDialect().generate(table("SQLSERVER")).getSql();
        assertThat(sql).contains("CREATE TABLE [demo].[sample]");
        assertThat(sql).contains("[id] bigint NOT NULL IDENTITY(1,1)");
        assertThat(sql).contains("[name] nvarchar(64) NOT NULL");
        assertThat(sql).contains("EXEC sp_addextendedproperty @name=N'MS_Description'");
    }

    @Test
    @DisplayName("SQLite：自增绑定在主键列，弱类型")
    void sqlite() {
        String sql = new SqliteDialect().generate(table("SQLITE")).getSql();
        assertThat(sql).contains("CREATE TABLE IF NOT EXISTS \"demo\".\"sample\"");
        assertThat(sql).contains("\"id\" integer NOT NULL PRIMARY KEY AUTOINCREMENT");
        assertThat(sql).contains("\"amount\" numeric");
    }

    @Test
    @DisplayName("Impala：外部表 + 分区列单独声明 + PARQUET，无主键/自增")
    void impala() {
        TableMeta t = table("IMPALA");
        t.setExternalTable(true);
        t.setTableOptions("STORED AS PARQUET");
        String sql = new ImpalaDialect().generate(t).getSql();
        assertThat(sql).startsWith("CREATE EXTERNAL TABLE");
        assertThat(sql).contains("`name` string NOT NULL COMMENT '名称'");
        assertThat(sql).contains("PARTITIONED BY (`dt` string)");
        assertThat(sql).doesNotContain("PRIMARY KEY");
        assertThat(sql).doesNotContain("AUTO_INCREMENT");
        assertThat(sql).contains("STORED AS PARQUET");
        assertThat(sql).contains("COMMENT '示例表'");
    }

    @Test
    @DisplayName("Hive：IF NOT EXISTS + 分区列单独声明")
    void hive() {
        String sql = new HiveDialect().generate(table("HIVE")).getSql();
        assertThat(sql).contains("CREATE TABLE IF NOT EXISTS");
        assertThat(sql).contains("PARTITIONED BY (`dt` string)");
    }

    @Test
    @DisplayName("ClickHouse：强类型 + PARTITION BY + 不支持表注释时降级告警")
    void clickHouse() {
        com.allst.springboot.ddl.dialect.DdlOutput out = new ClickHouseDialect().generate(table("CLICKHOUSE"));
        assertThat(out.getSql()).contains("`id` Int64 NOT NULL COMMENT '主键'");
        assertThat(out.getSql()).contains("`amount` Decimal(12,2)");
        assertThat(out.getSql()).contains("PARTITION BY (`dt`)");
        assertThat(out.getWarnings()).anyMatch(w -> w.contains("不支持表注释"));
    }

    @Test
    @DisplayName("Doris：UNIQUE KEY 表主键 + PARTITION BY")
    void doris() {
        String sql = new DorisDialect().generate(table("DORIS")).getSql();
        assertThat(sql).contains("UNIQUE KEY (`id`)");
        assertThat(sql).contains("PARTITION BY (`dt`)");
        assertThat(sql).contains("`amount` decimal(12,2)");
    }

    @Test
    @DisplayName("GENERIC 兜底：ANSI 近似写法 + 能力缺失告警")
    void generic() {
        com.allst.springboot.ddl.dialect.DdlOutput out = new GenericDialect().generate(table("UNKNOWN_DB"));
        assertThat(out.getSql()).contains("CREATE TABLE \"demo\".\"sample\"");
        assertThat(out.getSql()).contains("\"name\" varchar(64) NOT NULL");
        assertThat(out.getWarnings()).anyMatch(w -> w.contains("不支持表注释"));
        assertThat(out.getWarnings()).anyMatch(w -> w.contains("不支持列注释"));
        assertThat(out.getWarnings()).anyMatch(w -> w.contains("不支持分区"));
    }

    @Test
    @DisplayName("类型体系自治：Impala 不认识 BLOB 就明确报错，不猜类型")
    void unknownLogicalTypeFails() {
        TableMeta bad = TableMeta.builder().dialect("IMPALA").tableName("bad")
                .column(ColumnMeta.builder().columnName("blob_col").logicalType(BLOB).ordinal(0).build())
                .build();
        assertThatThrownBy(() -> new ImpalaDialect().generate(bad))
                .isInstanceOf(BizException.class)
                .hasMessageContaining("不支持逻辑类型 BLOB");
    }

    @Test
    @DisplayName("Builder 校验：重复列名与重复 ordinal 直接失败")
    void builderValidation() {
        ColumnMeta a = ColumnMeta.builder().columnName("a").logicalType(INT).ordinal(0).build();
        ColumnMeta b = ColumnMeta.builder().columnName("a").logicalType(INT).ordinal(1).build();
        assertThatThrownBy(() -> TableMeta.builder().tableName("t").dialect("MYSQL")
                .columns(a, b).build())
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("列名重复");
        ColumnMeta c = ColumnMeta.builder().columnName("c").logicalType(INT).ordinal(0).build();
        assertThatThrownBy(() -> TableMeta.builder().tableName("t").dialect("MYSQL")
                .columns(a, c).build())
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("ordinal 重复");
    }

    @Test
    @DisplayName("列顺序按 ordinal 稳定输出，与添加顺序无关")
    void stableColumnOrder() {
        TableMeta t = TableMeta.builder().dialect("MYSQL").tableName("ordered")
                .column(ColumnMeta.builder().columnName("third").logicalType(INT).ordinal(2).build())
                .column(ColumnMeta.builder().columnName("first").logicalType(INT).ordinal(0).build())
                .column(ColumnMeta.builder().columnName("second").logicalType(INT).ordinal(1).build())
                .build();
        String sql = new MySqlDialect().generate(t).getSql();
        assertThat(sql.indexOf("`first`")).isLessThan(sql.indexOf("`second`"));
        assertThat(sql.indexOf("`second`")).isLessThan(sql.indexOf("`third`"));
    }

    @Test
    @DisplayName("路由：注册方言命中，未注册落到 GENERIC")
    void routerFallback() {
        DialectRouter router = new DialectRouter(Arrays.asList(new MySqlDialect(), new GenericDialect()));
        assertThat(router.route("mysql").name()).isEqualTo("MYSQL");
        assertThat(router.route("CLICKHOUSE").name()).isEqualTo("GENERIC");
        assertThat(router.isFallback("MYSQL")).isFalse();
        assertThat(router.isFallback("CLICKHOUSE")).isTrue();
    }
}
