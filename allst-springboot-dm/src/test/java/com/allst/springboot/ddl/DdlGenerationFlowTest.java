package com.allst.springboot.ddl;

import com.allst.springboot.common.BizException;
import com.allst.springboot.ddl.dialect.DialectRouter;
import com.allst.springboot.ddl.generation.DdlExportService;
import com.allst.springboot.ddl.generation.DdlGenerator;
import com.allst.springboot.ddl.generation.DdlPlan;
import com.allst.springboot.ddl.generation.DialectScript;
import com.allst.springboot.ddl.meta.MetadataSeeder;
import com.allst.springboot.ddl.meta.TableMeta;
import com.allst.springboot.ddl.meta.TableMetaRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Collectors;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * 从 H2 里的元数据出发，跑通「读元数据 → 按方言分组 → 生成 → 导出 → 下载路径校验」。
 */
@SpringBootTest
@ActiveProfiles("test")
class DdlGenerationFlowTest {

    @Autowired
    private DialectRouter router;

    @Autowired
    private DdlGenerator generator;

    @Autowired
    private DdlExportService exporter;

    @Autowired
    private MetadataSeeder seeder;

    @Autowired
    private TableMetaRepository repository;

    @BeforeEach
    void setUp() {
        seeder.seed();
    }

    @Test
    @DisplayName("Spring 自动装配 10 个方言，未注册名走兜底")
    void routerDiscoversAllDialects() {
        assertThat(router.names()).hasSize(10);
        assertThat(router.names()).contains("MYSQL", "POSTGRESQL", "ORACLE", "SQLSERVER", "SQLITE",
                "IMPALA", "HIVE", "CLICKHOUSE", "DORIS", "GENERIC");
        assertThat(router.route("unknown").name()).isEqualTo("GENERIC");
    }

    @Test
    @DisplayName("按方言分组生成，Impala 脚本保留分区语法")
    void generateGroupsByDialect() {
        DdlPlan plan = generator.generate(repository.findAll());
        assertThat(plan.getTableCount()).isEqualTo(5);
        assertThat(plan.getScripts()).hasSize(5);
        DialectScript impala = plan.getScripts().stream()
                .filter(s -> "IMPALA".equals(s.getDialect()))
                .findFirst().orElseThrow();
        assertThat(impala.getSql()).contains("CREATE EXTERNAL TABLE");
        assertThat(impala.getSql()).contains("PARTITIONED BY (`dt` string)");
        assertThat(impala.getSql()).contains("STORED AS PARQUET");
    }

    @Test
    @DisplayName("导出按方言生成 UTF-8 文件，内容含文件头")
    void exportWritesFiles() throws IOException {
        DdlPlan plan = generator.generate(repository.findAll());
        List<DdlExportService.ExportedFile> files = exporter.export(plan);
        assertThat(files).hasSize(5);
        for (DdlExportService.ExportedFile file : files) {
            Path path = exporter.resolve(file.getFileName());
            assertThat(Files.exists(path)).isTrue();
            String content = new String(Files.readAllBytes(path), StandardCharsets.UTF_8);
            assertThat(content).contains("Generated by allst-springboot-dm");
            assertThat(content).contains("CREATE");
            assertThat(file.getSize()).isGreaterThan(0);
        }
        List<String> listed = exporter.listFiles();
        assertThat(listed).containsAll(files.stream()
                .map(DdlExportService.ExportedFile::getFileName).collect(Collectors.toList()));
    }

    @Test
    @DisplayName("覆盖方言：同一批 MySQL 元数据生成 Impala 脚本")
    void overrideDialect() {
        List<TableMeta> mysqlTables = repository.findByDialectOrderByIdAsc("MYSQL");
        DdlPlan plan = generator.generate("IMPALA", mysqlTables);
        assertThat(plan.getScripts()).hasSize(1);
        assertThat(plan.getScripts().get(0).getDialect()).isEqualTo("IMPALA");
        assertThat(plan.getScripts().get(0).getTables().get(0).getSql()).contains("CREATE TABLE");
    }

    @Test
    @DisplayName("下载路径防穿越：拒绝 ../ 与子目录")
    void pathTraversalRejected() {
        assertThatThrownBy(() -> exporter.resolve("../secret.sql"))
                .isInstanceOf(BizException.class)
                .hasMessageContaining("非法文件名");
        assertThatThrownBy(() -> exporter.resolve("sub/ddl.sql"))
                .isInstanceOf(BizException.class);
    }
}
