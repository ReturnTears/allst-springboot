package com.allst.springboot.ddl.generation;

import com.allst.springboot.ddl.dialect.DdlDialect;
import com.allst.springboot.ddl.dialect.DdlOutput;
import com.allst.springboot.ddl.dialect.DialectRouter;
import com.allst.springboot.ddl.meta.TableMeta;
import org.springframework.stereotype.Component;

import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * 外观门面 + Stream 编排：调用方只给一批 TableMeta，拿回按方言分组的脚本。
 *
 * <p>Stream发力点：
 * <ul>
 *   <li>groupingBy(dialect) 一次分组，每种方言只查一次路由；</li>
 *   <li>sorted(tableName) 保证输出顺序稳定；</li>
 *   <li>joining 拼装文件头与正文，不用 StringBuilder 做副作用拼接。</li>
 * </ul>
 * 注意这里故意用顺序流：DDL 生成是轻量 CPU 活，parallelStream 的分组与
 * StringBuilder 线程安全开销反而更大。
 */
@Component
public class DdlGenerator {

    private final DialectRouter router;

    public DdlGenerator(DialectRouter router) {
        this.router = router;
    }

    public DdlPlan generate(List<TableMeta> tables) {
        if (tables == null || tables.isEmpty()) {
            return new DdlPlan(Collections.emptyList());
        }
        Map<String, List<TableMeta>> grouped = tables.stream()
                .collect(Collectors.groupingBy(
                        t -> normalize(t.getDialect()),
                        LinkedHashMap::new,
                        Collectors.toList()));
        List<DialectScript> scripts = grouped.entrySet().stream()
                .map(e -> buildScript(e.getKey(), e.getValue()))
                .collect(Collectors.toList());
        return new DdlPlan(scripts);
    }

    /** 覆盖方言：同一批表换一个方言看效果 */
    public DdlPlan generate(String dialectOverride, List<TableMeta> tables) {
        if (dialectOverride == null || dialectOverride.isBlank()) {
            return generate(tables);
        }
        if (tables == null || tables.isEmpty()) {
            return new DdlPlan(Collections.emptyList());
        }
        return new DdlPlan(Collections.singletonList(
                buildScript(normalize(dialectOverride), tables)));
    }

    private DialectScript buildScript(String dialectName, List<TableMeta> tables) {
        DdlDialect dialect = router.route(dialectName);
        boolean fallback = router.isFallback(dialectName);
        List<TableDdl> ddls = tables.stream()
                .sorted(Comparator.comparing(TableMeta::getTableName, String.CASE_INSENSITIVE_ORDER))
                .map(t -> {
                    DdlOutput output = dialect.generate(t);
                    List<String> warnings = new ArrayList<>(output.getWarnings());
                    if (fallback) {
                        warnings.add(0, "方言 " + dialectName + " 未注册，使用 GENERIC 通用降级输出");
                    }
                    return new TableDdl(t.getSchemaName(), t.getTableName(), output.getSql(), warnings);
                })
                .collect(Collectors.toList());
        return new DialectScript(dialectName, fallback, ddls, header(dialectName, fallback, ddls.size()));
    }

    private String header(String dialect, boolean fallback, int tableCount) {
        return String.join("\n",
                "-- ============================================================",
                "-- Generated by allst-springboot-dm · DDL Generator",
                "-- Dialect : " + dialect,
                "-- Tables  : " + tableCount,
                "-- Fallback: " + (fallback ? "YES (GENERIC)" : "no"),
                "-- Time    : " + Instant.now(),
                "-- ============================================================");
    }

    private static String normalize(String s) {
        return s == null ? "" : s.trim().toUpperCase(Locale.ROOT);
    }
}
